generated AS (
    -- generate_series(1, 100) makes the numbers 1, 2, 3 ... 100 (one row each).
    -- "% 10", "% 12", "% 7" rotate through the lists, so every saree gets a different mix.
    SELECT g,
           (ARRAY['Kanjeevaram','Banarasi','Mysore Silk','Pochampally','Mangalagiri',
                  'Gadwal','Uppada','Patola','Soft Silk','Chanderi'])[1 + g % 10]     AS weave,
           (ARRAY['Red','Maroon','Green','Blue','Yellow','Pink','Orange','Purple',
                  'Beige','White','Black','Teal'])[1 + g % 12]                        AS color,
           (ARRAY['zari border','temple border','floral buttas','checks',
                  'peacock motifs','contrast pallu','stripes'])[1 + g % 7]            AS motif
    FROM generate_series(1, 100) AS g
)
INSERT INTO products (sku, name, description, category, weave, occasion, color,
                      price, stock, image_url, bestseller, active)
SELECT
    'SAR-' || LPAD((13 + gen.g)::text, 4, '0'),                     -- SAR-0014 ... SAR-0113
    gen.color || ' ' || gen.weave || ' saree with ' || gen.motif,   -- e.g. "Green Banarasi saree with checks"
    w.description,
    'Sarees',
    gen.weave,
    CASE                                                            -- grand weaves are bridal/festive
        WHEN gen.weave IN ('Kanjeevaram', 'Banarasi', 'Patola')
            THEN CASE WHEN (gen.g / 10) % 2 = 0 THEN 'BRIDAL' ELSE 'FESTIVE' END
        WHEN gen.weave IN ('Mangalagiri', 'Chanderi', 'Soft Silk')
            THEN 'EVERYDAY'
        ELSE CASE WHEN (gen.g / 10) % 2 = 0 THEN 'FESTIVE' ELSE 'EVERYDAY' END
    END,
    gen.color,
    ROUND(w.base_price * (100 + (gen.g * 37) % 60) / 100.0 / 50) * 50,  -- base price up to +59%, rounded to 50
    (gen.g * 7) % 15,                                               -- stock 0..14 (some are out of stock)
    w.photos[1 + (gen.g / 10) % array_length(w.photos, 1)],         -- rotate through that weave's photos
    gen.g % 9 = 0,                                                  -- every 9th saree is a bestseller
    TRUE
FROM generated gen
JOIN weave_info w ON w.weave = gen.weave;